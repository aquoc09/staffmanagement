    public List<Department> getDepartments() {
        List<Department> departments = new ArrayList<>();
        if (!flagStatus) {
            departments.addAll(this.parent.getDepartmentBus().getList());
            return departments;
        } else {
            var index = parent.getIndexSelected(EntityType.DEP);
            var departmentTmp = parent.getDepartmentBus().getList().get(index);
            departments.add(departmentTmp);
            return departments;
        }
    }


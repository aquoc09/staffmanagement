    @Override
    public void actionPerformed(ActionEvent e) {
        var obj = e.getSource();
        if (obj.equals(btnAdd)) {
            var id = txtId.getText();
            if (employeeBus.findById(id) == null) {
                try {
                    var name = txtName.getText();
                    var cccd = txtCCCD.getText();
                    var sex = getSex();
                    var dob = getDob();
                    var email = txtEmail.getText();
                    var address = txtAddress.getText();
                    var department = getDepartment();
                    var position = txtPosition.getText();
                    var baseSalary = Long.parseLong(txtBaseSalary.getText());
                    Employee emp = new Employee(id, cccd, name, sex, dob,
                            email, address, department, position, baseSalary);
                    if (employeeBus.add(emp)) {
                        parent.showEmployee(emp);
                        if (department != null) {
                            int index = parent.getDepartmentBus()
                                    .getList().indexOf(department);
                            parent.getDepartmentBus()
                                    .getList().get(index).getEmpList().add(emp);
                        }
                        JOptionPane.showMessageDialog(parent,
                                "Thêm nhân viên thành công");
                    }
                } catch (InvalidEmailException ex) {
                    Logger.getLogger(AddEmployeeDialogGUI.class.getName())
                            .log(Level.SEVERE, null, ex);
                    JOptionPane.showMessageDialog(parent,
                            "Email không hợp lệ");
                } catch (InvalidEmployeeIDException ex) {
                    Logger.getLogger(AddEmployeeDialogGUI.class.getName())
                            .log(Level.SEVERE, null, ex);
                    JOptionPane.showMessageDialog(parent,
                            "Id không hợp lệ");
                }
            } else {
                JOptionPane.showMessageDialog(parent,
                        "Nhân viên " + id + " đã tồn tại");
            }

        }
        if (obj.equals(btnCancel)) {
            this.dispose();
        }
    }

    public Date getDob() {
        var format = "dd/MM/yyyy";
        SimpleDateFormat dateFormat = new SimpleDateFormat(format);
        Date date = null;
        try {
            date = dateFormat.parse(txtDob.getText());
        } catch (ParseException ex) {
            ex.getMessage();
            JOptionPane.showMessageDialog(parent,
                    "Định dạng ngày sinh nhập vào không hơp lệ! 'dd/MM/yyyy'"
                    + date);
        }
        return date;
    }

    public boolean getSex() {
        var obj = boxSex.getSelectedItem();
        return obj.equals("Nam");
    }

    public Department getDepartment() {
        var obj = boxDeparment.getSelectedItem();
        List<Department> departments = getDepartments();
        for (var department : departments) {
            if (department.getName().equalsIgnoreCase(obj.toString())) {
                return department;
            }
        }
        return null;
    }


    public EditEmployeeDialogGUI(java.awt.Frame parent, boolean modal,
             boolean flagStatus, int index, DefaultTableModel tableModel,
             EmployeeBUS employeeBUS) {
        super(parent, modal);
        this.parent = (MainPageGUI) parent;
        this.flagStatus = flagStatus;
        this.tableModel = this.parent.getTableModel(EntityType.EMP);
        if (!flagStatus) {
            this.indexSelected = this.parent.getIndexSelected(EntityType.EMP);
            this.employeeBus = this.parent.getEmployeeBus();
        } else {
            this.employeeBus = employeeBUS;
            this.tableListEmpModel = tableModel;
            this.indexSelected = index;
        }

        initComponents();
        addActionListener();
        setInfo();
    }

    public List<Department> getDepartments() {
        List<Department> departments = new ArrayList<>();
        if (!flagStatus) {
            departments.addAll(this.parent.getDepartmentBus().getList());
            return departments;
        } else {
            var index = parent.getIndexSelected(EntityType.DEP);
            var departmentTmp = parent.getDepartmentBus().getList().get(index);
            departments.add(departmentTmp);
            return departments;
        }
    }


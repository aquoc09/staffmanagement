    @Override
    public void actionPerformed(ActionEvent e) {
        var obj = e.getSource();
        if (obj.equals(btnCancel)) {
            this.dispose();
        }
        if (obj.equals(btnEdit)) {
            int choice = JOptionPane.showConfirmDialog(parent,
                    "Bạn có muốn sửa không?");
            if (choice == 0) {
                Employee emp = editEmployee();
                tableModel.removeRow(indexSelected);
                tableModel.fireTableDataChanged();
                this.parent.showEmployee(emp);
                JOptionPane.showMessageDialog(parent,
                        "Sửa thông tin thành công!");
            }

        }
    }

    private void addActionListener() {
        btnCancel.addActionListener(this);
        btnEdit.addActionListener(this);
    }

    private void setInfo() {
        Employee emp = (Employee) employeeBus.getList().get(indexSelected);
        txtID.setText(emp.getId());
        txtName.setText(emp.getFullName());
        txtCCCD.setText(emp.getCccd());
        setSex(emp);

        //format form dob
        var format = "dd/MM/yyyy";
        SimpleDateFormat dateFormat = new SimpleDateFormat(format);
        Date date = emp.getDob();
        txtDob.setText(dateFormat.format(date));

        txtEmail.setText(emp.getEmail());
        txtAddress.setText(emp.getAddress());
        setDepartment(emp);
        txtPosition.setText(emp.getPosition());
        txtBaseSalary.setText(String.valueOf(emp.getBaseSalary()));

    }

    private void setSex(Employee emp) {
        boolean sex = emp.getSex();
        if (sex) {
            boxSex.setSelectedIndex(0);
        } else {
            boxSex.setSelectedIndex(1);
        }
    }

    private void setDepartment(Employee emp) {
        Department dep = emp.getDepartment();
        for (int i = 0; i < boxDeparment.getItemCount(); i++) {
            if (boxDeparment.getItemAt(i).compareToIgnoreCase(dep.getName()) == 0) {
                boxDeparment.setSelectedIndex(i);
                break;
            }
        }
    }

    public Date getDob() {
        var format = "dd/MM/yyyy";
        SimpleDateFormat dateFormat = new SimpleDateFormat(format);
        Date date = null;
        try {
            date = dateFormat.parse(txtDob.getText());
        } catch (ParseException ex) {
            ex.getMessage();
            JOptionPane.showMessageDialog(parent,
                    "Định dạng ngày sinh nhập vào không hơp lệ! 'dd/MM/yyyy'"
                    + date);
        }
        return date;
    }

    public boolean getSex() {
        var obj = boxSex.getSelectedItem();
        return obj.equals("Nam");
    }

    public Department getDepartment() {
        var obj = boxDeparment.getSelectedItem();
        List<Department> departments = getDepartments();
        for (var department : departments) {
            if (department.getName().equalsIgnoreCase(obj.toString())) {
                return department;
            }
        }
        return null;
    }

    private Employee editEmployee() {
        Employee emp = new Employee();
        var name = txtName.getText();
        var cccd = txtCCCD.getText();
        var sex = getSex();
        var dob = getDob();
        var email = txtEmail.getText();
        var address = txtAddress.getText();
        var department = getDepartment();
        var position = txtPosition.getText();
        var baseSalary = Long.parseLong(txtBaseSalary.getText());

        if (!(name.isEmpty() && cccd.isEmpty() && email.isEmpty() && address.isEmpty()
                && position.isEmpty())) {
            emp = this.parent.getEmployeeBus().getList().get(indexSelected);
            emp.setFullName(name);
            emp.setCccd(cccd);
            emp.setDob(dob);
            emp.setSex(sex);
            try {
                emp.setEmail(email);
            } catch (InvalidEmailException ex) {
                Logger.getLogger(EditEmployeeDialogGUI.class.getName())
                        .log(Level.SEVERE, null, ex);
            }
            emp.setPosition(position);
            emp.setAddress(address);
            emp.setDepartment(department);
            emp.setBaseSalary(baseSalary);
        }
        return emp;
    }
